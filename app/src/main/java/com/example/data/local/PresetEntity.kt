package com.example.data.local

import androidx.room.Entity
import androidx.room.PrimaryKey
import com.example.data.model.FfxPreset

@Entity(tableName = "presets")
data class PresetEntity(
    @PrimaryKey val id: String,
    val name: String,
    val fileName: String,
    val category: String,
    val description: String,
    val sourceType: String,
    val presetFormat: String,
    val ffxVersion: String,
    val effectModules: List<String>,
    val unsupportedModules: List<String>,
    val tags: List<String>,
    val isFavorite: Boolean,
    val exposure: Double,
    val contrast: Double,
    val saturation: Double,
    val hueShift: Double,
    val temperature: Double,
    val tint: Double,
    val vignetteIntensity: Double,
    val glowIntensity: Double,
    val grainAmount: Double,
    val blurRadius: Double,
    val zoomPulse: Double,
    val shakeIntensity: Double,
    val rotationDegrees: Double,
    val speedMultiplier: Double,
    val letterboxRatio: Double,
    val lutSize: Int,
    val lutData: String,
    val rawHeaderSnippet: String,
    val usageCount: Long,
    val createdAtMillis: Long,
    val updatedAtMillis: Long,
) {
    fun toDomain(): FfxPreset = FfxPreset(
        id = id,
        name = name,
        fileName = fileName,
        category = category,
        description = description,
        sourceType = sourceType,
        presetFormat = presetFormat,
        ffxVersion = ffxVersion,
        effectModules = effectModules,
        unsupportedModules = unsupportedModules,
        tags = tags,
        isFavorite = isFavorite,
        exposure = exposure,
        contrast = contrast,
        saturation = saturation,
        hueShift = hueShift,
        temperature = temperature,
        tint = tint,
        vignetteIntensity = vignetteIntensity,
        glowIntensity = glowIntensity,
        grainAmount = grainAmount,
        blurRadius = blurRadius,
        zoomPulse = zoomPulse,
        shakeIntensity = shakeIntensity,
        rotationDegrees = rotationDegrees,
        speedMultiplier = speedMultiplier,
        letterboxRatio = letterboxRatio,
        lutSize = lutSize,
        lutData = lutData,
        rawHeaderSnippet = rawHeaderSnippet,
        usageCount = usageCount,
        createdAtMillis = createdAtMillis,
        updatedAtMillis = updatedAtMillis,
    )
}

fun FfxPreset.toEntity(
    resolvedId: String = id,
    createdAt: Long = createdAtMillis,
    updatedAt: Long = updatedAtMillis,
): PresetEntity = PresetEntity(
    id = resolvedId,
    name = name,
    fileName = fileName,
    category = category,
    description = description,
    sourceType = sourceType,
    presetFormat = presetFormat,
    ffxVersion = ffxVersion,
    effectModules = effectModules,
    unsupportedModules = unsupportedModules,
    tags = tags,
    isFavorite = isFavorite,
    exposure = exposure,
    contrast = contrast,
    saturation = saturation,
    hueShift = hueShift,
    temperature = temperature,
    tint = tint,
    vignetteIntensity = vignetteIntensity,
    glowIntensity = glowIntensity,
    grainAmount = grainAmount,
    blurRadius = blurRadius,
    zoomPulse = zoomPulse,
    shakeIntensity = shakeIntensity,
    rotationDegrees = rotationDegrees,
    speedMultiplier = speedMultiplier,
    letterboxRatio = letterboxRatio,
    lutSize = lutSize,
    lutData = lutData,
    rawHeaderSnippet = rawHeaderSnippet,
    usageCount = usageCount,
    createdAtMillis = createdAt,
    updatedAtMillis = updatedAt,
)
